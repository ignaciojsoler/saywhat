// Turn out/whisper.json into src/lib/captions/promo-transcript.ts.
// Whisper's timings are kept; the words themselves are replaced 1:1 with the script text
// (fixes "say what" -> "Saywhat", casing and punctuation). Fails loudly if they don't line up.
//
// Usage: node scripts/make-transcript.mjs
import { readFileSync, writeFileSync } from "node:fs"
import { execFileSync } from "node:child_process"

const SCRIPT =
  "Your videos deserve captions that pop. Drop in a clip. Saywhat transcribes it, word by word. " +
  "Pick a style: Pop, Karaoke, Punch, Boxed, or Clean. Wrong word? Just fix it, like editing a doc. " +
  "Then export an MP4 with captions burned in, or grab the SRT. " +
  "It all runs in your browser, and nothing gets stored. " +
  "No subscription. Pay per video, and your first three are free. Saywhat."

const root = new URL("..", import.meta.url).pathname
const raw = JSON.parse(readFileSync(`${root}out/whisper.json`, "utf8")).words
const norm = (w) => w.toLowerCase().replace(/[^a-z0-9]/g, "")

// Merge "say" + "what" into one timed token.
const timed = []
for (let i = 0; i < raw.length; i++) {
  const w = raw[i]
  if (norm(w.word) === "say" && raw[i + 1] && norm(raw[i + 1].word) === "what") {
    timed.push({ word: "saywhat", start: w.start, end: raw[i + 1].end })
    i++
  } else timed.push(w)
}

const tokens = SCRIPT.split(/\s+/)
if (tokens.length !== timed.length) throw new Error(`script has ${tokens.length} words, whisper ${timed.length}`)
const round = (n) => Math.round(n * 100) / 100
const words = tokens.map((w, i) => {
  if (norm(w) !== norm(timed[i].word)) console.warn(`fix: "${timed[i].word}" -> "${w}"`)
  return { w, s: round(timed[i].start), e: round(timed[i].end) }
})

const duration = parseFloat(
  execFileSync("ffprobe", ["-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", `${root}voiceover.wav`]).toString(),
)

const out = `import type { Word } from "./types"

/**
 * Word-level timings of the landing promo voiceover (public/promo.mp4).
 * Generated by video/scripts/make-transcript.mjs from a Whisper (Cloudflare Workers AI)
 * transcription, with the words corrected against video/script.md. Do not edit by hand.
 */
export const PROMO_WORDS: Word[] = [
${words.map((w) => `  { w: ${JSON.stringify(w.w)}, s: ${w.s}, e: ${w.e} },`).join("\n")}
]

/** Length of the promo video/voiceover, in seconds. */
export const PROMO_DURATION = ${round(duration)}
`
writeFileSync(`${root}../src/lib/captions/promo-transcript.ts`, out)
writeFileSync(`${root}src/words.json`, JSON.stringify({ words, duration: round(duration) }, null, 2))
console.log(`${words.length} words, ${round(duration)} s`)
